SELECT 
    EMPLOYEE_ID,
    FIRST_NAME,
    LAST_NAME
FROM HR.EMPLOYEES
WHERE EMPLOYEE_ID IN (SELECT MANAGER_ID 
        FROM HR.EMPLOYEES);
-- 2)
SELECT DISTINCT 
    M.EMPLOYEE_ID,
    M.FIRST_NAME,
    M.LAST_NAME
FROM HR.EMPLOYEES M
JOIN HR.EMPLOYEES E 
    ON M.EMPLOYEE_ID = E.MANAGER_ID;
-- DISTINCT ISTIFADE ETMEKLE DUZLEIR SEARCH

-- TASK 10
SELECT 
    M.FIRST_NAME AS MENECER_ADI,
    M.LAST_NAME AS MENECER_SOYADI,
    COUNT(E.EMPLOYEE_ID) AS TABE_SAYI,
    ROUND(AVG(E.SALARY)) AS TABELERIN_ORTA_MAASI
FROM 
    HR.EMPLOYEES M
INNER JOIN 
    HR.EMPLOYEES E ON M.EMPLOYEE_ID = E.MANAGER_ID
GROUP BY 
    M.EMPLOYEE_ID, 
    M.FIRST_NAME, 
    M.LAST_NAME
HAVING 
    COUNT(E.EMPLOYEE_ID) > 5
ORDER BY 
    TABE_SAYI DESC;