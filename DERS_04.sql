-- TASK 1
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    M.FIRST_NAME AS MENERCER_ADI,
    M.LAST_NAME AS MENECER_SOYADI
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M
    ON E.MANAGER_ID = M.EMPLOYEE_ID;

-- TASK 2
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    M.FIRST_NAME AS MENERCER_ADI,
    M.LAST_NAME AS MENECER_SOYADI
FROM HR.EMPLOYEES E
LEFT JOIN HR.EMPLOYEES M
    ON E.MANAGER_ID = M.EMPLOYEE_ID;

-- TASK 3
SELECT
    FIRST_NAME,
    LAST_NAME,
    DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (SELECT
                            DEPARTMENT_ID
                        FROM HR.DEPARTMENTS
                        WHERE LOCATION_ID = 1700);
                
-- TASK 4
SELECT
    E.FIRST_NAME,
    E.LAST_NAME
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M
    ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE 
    M.FIRST_NAME = 'Steven' 
    AND M.LAST_NAME = 'King';

-- TASK 5
SELECT 
    E.FIRST_NAME,
    E.LAST_NAME,
    E.SALARY,
    M.FIRST_NAME AS MENECER_ADI,
    M.SALARY AS MENECER_MAASI
FROM 
    HR.EMPLOYEES E
INNER JOIN 
    HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE 
    E.SALARY > M.SALARY;

-- TASK 6
SELECT 
    E.FIRST_NAME,
    E.LAST_NAME,
    E.DEPARTMENT_ID,
    M.FIRST_NAME AS MENECER_ADI,
    M.DEPARTMENT_ID AS MENECER_SOBESI
FROM 
    HR.EMPLOYEES E
INNER JOIN 
    HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE 
    E.DEPARTMENT_ID != M.DEPARTMENT_ID;

-- TASK 7
SELECT
    FIRST_NAME,
    LAST_NAME,
    JOB_ID,
    SALARY
FROM HR.EMPLOYEES
WHERE JOB_ID IN (SELECT
                    JOB_ID
                FROM HR.JOBS
                WHERE MIN_SALARY > 10000);

-- TASK 8
SELECT 
    FIRST_NAME, 
    LAST_NAME
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID
                       FROM HR.DEPARTMENTS
                       WHERE DEPARTMENT_NAME IN ('Sales', 'IT'));
