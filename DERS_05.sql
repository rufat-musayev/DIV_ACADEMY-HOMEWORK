-- TASK 1
SELECT
    FIRST_NAME || ' ' || UPPER(LAST_NAME) AS TAM_AD,
    SUBSTR(FIRST_NAME, 1, 1) || '. ' || LAST_NAME AS QISA_AD,
    EMAIL || '@company.com'
FROM HR.EMPLOYEES;

-- TASK 2
SELECT  
    FIRST_NAME,
    TO_CHAR(SALARY, 'FM999,999,999,990') || ' AZN' AS MAAS,
    TO_CHAR(SALARY * 12, 'FM999,999,999,990') || '.00' AS ILLIK_MAAS
FROM HR.EMPLOYEES;

-- TASK 3
SELECT
    HIRE_DATE AS ISE_GIRIS,
    EXTRACT(YEAR FROM HIRE_DATE) AS IL,
    TO_CHAR(HIRE_DATE, 'MONTH') AS AY_ADI,
    TO_CHAR(HIRE_DATE, 'DAY') AS HEFTE_GUNU
FROM HR.EMPLOYEES;  

-- TASK 4
SELECT  
    FIRST_NAME || ' ' || LAST_NAME AS ISCI,
    TO_CHAR(HIRE_DATE, 'DD.MONTH.YYYY') AS ISE_GIRIS,
    TRUNC(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)/12) || ' IL ' || TRUNC(MOD(MONTHS_BETWEEN(SYSDATE, HIRE_DATE),12)) || ' AY ' AS STAJ
FROM HR.EMPLOYEES;

-- TASK 5
SELECT 
    FIRST_NAME,
    HIRE_DATE,
    ADD_MONTHS(HIRE_DATE, 3) AS SINAQ_BITIR,
    LAST_DAY(HIRE_DATE) AS ILK_MAAS_GUNU,
    LAST_DAY(HIRE_DATE) - HIRE_DATE AS MAASA_QALAN_GUN
FROM HR.EMPLOYEES;
-- WITH DUAL
SELECT
    TO_DATE('28.02.2025', 'DD.MM.YYYY') AS DATA,
    ADD_MONTHS(TO_DATE('28.02.2025', 'DD.MM.YYYY'),3) AS ELAVE_3_AY
FROM DUAL;
-- CUNKI HER AY'DA FERGLI GUNLER VAR(28,29,30,31) VE NETICEDE GUN SAYI DEYISIR

-- TASK 6
SELECT 
    CONCAT(FIRST_NAME, ' ', LAST_NAME) || ', komissiya: ' || NVL2(COMMISSION_PCT,COSI, 'yoxdur') AS MELUMAT
FROM HR.EMPLOYEES
WHERE EXTRACT(MONTH FROM HIRE_DATE) = 3;
-- 1 CI SEHV NVL YOX NVL2 ISTIFADE OLUNMALIDIR CUNKI NVL 1 DE HEM STRING HEM INTEGER OLA BILER BU ISE SEHVDIR
-- 2 CI SEHV TO_CAHR YOX EXTRACT FUNCTION ISTIFADE OLUNMALIDIR
-- 3 CU SHEV ISE EXTRACT INTEGER KIMI CIXIR VE 3'U STRING YOX INT VERMEK LAZIMDI

-- TASK 7
SELECT 
    TO_CHAR(HIRE_DATE, 'MM') AS AY_NO,
    TO_CHAR(HIRE_DATE, 'Month') AS AY,
    COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY 
    TO_CHAR(HIRE_DATE, 'MM'),
    TO_CHAR(HIRE_DATE, 'Month')
ORDER BY AY_NO;
-- TABLE'I JANUARY-DECEMBER SIRALAYIR VE ONA GORE ISCI SAYIN VERIR

-- TASK 8
SELECT
    EMPLOYEE_ID,
    SUBSTR(FIRST_NAME,1,1)||LOWER(LAST_NAME)||LPAD(EMPLOYEE_ID, 4, '0')AS LOGIN,
    REPLACE(PHONE_NUMBER,'.') AS TELEFON
FROM HR.EMPLOYEES
WHERE LENGTH(LAST_NAME)>=7
ORDER BY LOGIN;

-- TASK 9
SELECT
    EXTRACT(YEAR FROM HIRE_DATE) AS IL,
    COUNT(*) AS ISCI_SAYI,
    TO_CHAR(MIN(HIRE_DATE),'DD,MM,YYYY') AS ILK_TARIX,
    TO_CHAR(MAX(HIRE_DATE),'DD,MM,YYYY') AS ILK_TARIX,
    TO_CHAR(ROUND(AVG(SALARY),2), '999,999,999,999') 
FROM HR.EMPLOYEES
GROUP BY EXTRACT(YEAR FROM HIRE_DATE)
ORDER BY IL ASC;


-- TASK 10
SELECT 
    FIRST_NAME,
    TO_CHAR(HIRE_DATE, 'Dy, DD.MM.YYYY') AS ISE_GIRIS,
    CASE 
        WHEN TO_CHAR(HIRE_DATE, 'Dy') IN ('Sat', 'Sun') 
            THEN 'Hefte sonu'
        ELSE 'Is gunu'
    END AS GUN_NOVU
FROM HR.EMPLOYEES;

-- B)
SELECT 
    TO_CHAR(HIRE_DATE, 'Day') AS GUN,
    COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
GROUP BY TO_CHAR(HIRE_DATE, 'Day')
ORDER BY ISCI_SAYI DESC;